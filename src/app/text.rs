pub fn low_battery_message(language: Language, percentage: u8) -> String {
    match language {
        Language::English => format!("Mouse battery is low: {percentage}%"),
        Language::SimplifiedChinese => format!("鼠标电量较低：{percentage}%"),
    }
}
